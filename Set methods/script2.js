//All set methods in date object

const mydate = new Date()

//setFullYear
mydate.setFullYear(2003)

//setMonth
mydate.setMonth(2) //index of month

//setDay
mydate.setDate(11)

//setHours
mydate.setHours(10)

//setMinutes
mydate.setMinutes(21)

//setSeconds
mydate.setSeconds(23)

//setMiliseconds
mydate.setMilliseconds(25)

//setTime
mydate.setTime(0)

